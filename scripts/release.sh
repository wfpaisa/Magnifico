#!/usr/bin/env bash
# One script for the whole release: checks, build, every package, checksums and
# upload to a GitHub release. The version comes from Cargo.toml.
#
#   scripts/release.sh                 checks + packages + upload (asks first)
#   scripts/release.sh --no-upload     build everything into dist/release only
#   scripts/release.sh --yes           upload without the confirmation prompt
#   scripts/release.sh --skip-checks   skip fmt / clippy / tests
#   scripts/release.sh --notes FILE    release notes (default: RELEASE_NOTES.md
#                                      if present, else generated by GitHub)
#
# Bump `version` in Cargo.toml and commit before running it.
set -euo pipefail

cd "$(dirname "$0")/.."

APP_ID=io.github.wfpaisa.Magnifico
UPLOAD=1 ASSUME_YES=0 CHECKS=1 NOTES=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --no-upload) UPLOAD=0 ;;
        --yes|-y) ASSUME_YES=1 ;;
        --skip-checks) CHECKS=0 ;;
        --notes) NOTES="${2:?--notes needs a file}"; shift ;;
        -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

VERSION="$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)"
TAG="v${VERSION}"
ARCH="$(uname -m)"
OUT="dist/release"
[[ -z "$NOTES" && -f RELEASE_NOTES.md ]] && NOTES="RELEASE_NOTES.md"

step() { printf '\n\033[1m=== %s ===\033[0m\n' "$*"; }

echo "Magnífico ${VERSION} (${TAG})"

# ---- preflight --------------------------------------------------------------
if [[ $UPLOAD -eq 1 ]]; then
    command -v gh >/dev/null || { echo "gh (GitHub CLI) is required to upload." >&2; exit 1; }
    gh auth status >/dev/null 2>&1 || { echo "Run 'gh auth login' first." >&2; exit 1; }
    if [[ -n "$(git status --porcelain)" ]]; then
        echo "Working tree has uncommitted changes; commit them first (or use --no-upload)." >&2
        exit 1
    fi
fi

step "Tools"
command -v cargo-deb >/dev/null || cargo install --locked cargo-deb
command -v cargo-generate-rpm >/dev/null || cargo install --locked cargo-generate-rpm
have_tool() { command -v "$1" >/dev/null || [[ -x "${HOME}/.local/bin/$1" ]]; }
if ! have_tool linuxdeploy || ! have_tool appimagetool; then
    scripts/setup-appimage-tools.sh
fi

# ---- checks -----------------------------------------------------------------
if [[ $CHECKS -eq 1 ]]; then
    step "Checks"
    cargo fmt --check
    cargo clippy --all-targets --locked -- -D warnings
    cargo test --locked
fi

# ---- packages ---------------------------------------------------------------
step "Cleaning old ${VERSION} artifacts"
rm -rf "$OUT"
rm -f dist/rpm/*"${VERSION}"*.rpm dist/deb/*"${VERSION}"*.deb dist/appimage/*"${VERSION}"*.AppImage
mkdir -p "$OUT"

step "RPM"
scripts/package-rpm.sh
step "DEB"
scripts/package-deb.sh
step "AppImage"
scripts/package-appimage.sh

step "Tarball"
NAME="magnifico-${VERSION}-linux-${ARCH}"
STAGE="build/tarball/${NAME}"
rm -rf build/tarball
mkdir -p "$STAGE"
install -m755 target/release/magnifico "$STAGE/magnifico"
install -m644 "data/${APP_ID}.desktop" "$STAGE/"
install -m644 "data/${APP_ID}.metainfo.xml" "$STAGE/"
install -m644 "data/icons/hicolor/scalable/apps/${APP_ID}.svg" "$STAGE/"
install -m644 "data/icons/hicolor/symbolic/apps/${APP_ID}-symbolic.svg" "$STAGE/"
install -m644 LICENSE "$STAGE/"
tar -C build/tarball -czf "${OUT}/${NAME}.tar.gz" "$NAME"

step "Collecting assets"
cp dist/rpm/*"${VERSION}"*.rpm dist/deb/*"${VERSION}"*.deb dist/appimage/*"${VERSION}"*.AppImage "$OUT/"
(cd "$OUT" && sha256sum -- * | grep -v ' SHA256SUMS$' > SHA256SUMS)
ls -lh "$OUT"

if [[ $UPLOAD -eq 0 ]]; then
    echo; echo "✅ Built ${VERSION} in ${OUT} (upload skipped)."
    exit 0
fi

# ---- upload -----------------------------------------------------------------
step "Upload"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
if gh release view "$TAG" >/dev/null 2>&1; then
    ACTION="replace the assets of the existing release ${TAG}"
else
    ACTION="push ${BRANCH} and create release ${TAG}"
fi
if [[ $ASSUME_YES -eq 0 ]]; then
    read -r -p "About to ${ACTION} on GitHub. Continue? [y/N] " answer
    [[ "$answer" =~ ^[yY]$ ]] || { echo "Aborted. Packages are in ${OUT}."; exit 0; }
fi

git push origin "$BRANCH"
if gh release view "$TAG" >/dev/null 2>&1; then
    gh release upload "$TAG" "$OUT"/* --clobber
else
    if [[ -n "$NOTES" ]]; then NOTES_ARGS=(--notes-file "$NOTES"); else NOTES_ARGS=(--generate-notes); fi
    gh release create "$TAG" "$OUT"/* --target "$BRANCH" --title "Magnífico ${VERSION}" "${NOTES_ARGS[@]}"
fi
echo; echo "✅ Released ${TAG}: $(gh release view "$TAG" --json url -q .url)"
